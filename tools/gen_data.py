class Symbols:
    """Resolves relocation targets to C expressions."""

    def __init__(self, elves, index, per_seg, clashes, abs_syms):
        self.elves = elves
        self.index = index
        self.clashes = {o: set(c) for o, c in clashes.items()}
        self.abs = abs_syms
        self.gen = {}          # (seg, name) -> Label   (seg None for non-overlay)
        self.gen_by_name = defaultdict(list)
        for seg, labels in per_seg.items():
            for l in labels:
                self.gen_by_name[l.name].append(l)
        # address -> objects for interior lookups: (start, end, name, seg)
        self.objects = defaultdict(list)
        for seg, e in elves.items():
            for n, (addr, size, typ) in e.defined.items():
                if typ == "STT_OBJECT" or (typ == "STT_NOTYPE" and not SEG_SYM_RE.search(n)):
                    self.objects[seg].append((addr, addr + max(size, 1), n))
        for seg, labels in per_seg.items():
            for l in labels:
                self.objects[seg].append((l.vram, l.vram + max(l.size, 1), l.name))
        for seg in self.objects:
            self.objects[seg].sort()
        self.starts = {seg: [o[0] for o in objs] for seg, objs in self.objects.items()}
        self.funcs = defaultdict(dict)  # seg -> addr -> function name (C-declared names preferred)
        for seg, e in elves.items():
            for n, (addr, size, typ) in e.defined.items():
                if typ == "STT_FUNC" and (addr not in self.funcs[seg] or n in index.func):
                    self.funcs[seg][addr] = n
        self.ovl_fn_ptrs = {}  # overlay VRAM -> [(overlay, function)] referenced from non-overlay data
        self.ovl_fn_sigs = {}  # overlay VRAM -> thunk signature

    def func_at(self, addr, seg):
        for s in self.visible_segs(seg):
            n = self.funcs[s].get(addr)
            if n is not None and n in self.index.func:
                return n
        return None

    def overlay_fn_dispatcher(self, addr):
        """(name, sig) of a generated thunk calling the function at `addr` in the active overlay (ovl_entry.c);
        the thunk takes the widest signature among the candidate targets."""
        targets = []
        for ovl in OVERLAYS:
            n = self.funcs[ovl].get(addr)
            if n is not None and n in self.index.func_defined and self.index.func.get(n) is not None:
                targets.append((ovl, n))
        if not targets:
            return None
        self.ovl_fn_ptrs[addr] = targets
        sigs = [self.index.func[n] for _, n in targets]
        sig = max(sigs, key=lambda s: (len(s[1]) if s[1] != ("void",) else 0, s[0] != "void"))
        self.ovl_fn_sigs[addr] = sig
        return f"port_ovlfn_{addr:08X}", sig

    def asm_name(self, name, seg_of_def):
        if seg_of_def in OVERLAYS and name in self.clashes[seg_of_def]:
            return f"{seg_of_def}__{name}"
        return name

    def visible_segs(self, seg):
        return [seg, "global", "boot"] if seg in OVERLAYS else ["global", "boot"]

    def find_container(self, addr, seg):
        for s in self.visible_segs(seg):
            objs = self.objects[s]
            i = bisect.bisect_right(self.starts[s], addr) - 1
            # walk back over objects starting at or before addr; the innermost (latest start) containing wins
            while i >= 0 and addr - objs[i][0] < 0x100000:
                start, end, n = objs[i]
                if start <= addr < end:
                    return n, addr - start, s
                i -= 1
        return None

    def def_seg(self, name, seg):
        """Segment that defines `name` as seen from `seg`, or None."""
        for s in self.visible_segs(seg):
            if name in self.elves[s].defined:
                return s
            for l in self.gen_by_name.get(name, []):
                if l.seg == s:
                    return s
        return None

    def classify(self, name, seg):
        """-> ('func', asm, sig) | ('data', asm) | ('abs', value) | None"""
        if name in self.index.func or name in self.index.func_defined:
            fseg, static = self.index.func_defined.get(name, (None, False))
            if static:
                return ("error", f"function {name} is static in C")
            sig = self.index.func.get(name)
            if sig is None:
                return ("error", f"function {name} has no lowerable prototype")
            dseg = self.def_seg(name, seg) or fseg or seg
            return ("func", self.asm_name(name, dseg), sig)
        for l in self.gen_by_name.get(name, []):
            if l.seg in self.visible_segs(seg):
                return ("data", self.asm_name(name, l.seg))
        if name in self.index.c_defined:
            dseg, static = self.index.c_defined[name]
            if static:
                return ("error", f"data {name} is static in C")
            return ("data", self.asm_name(name, self.def_seg(name, seg) or dseg))
        for s in self.visible_segs(seg):
            if name in self.elves[s].defined:
                addr, size, typ = self.elves[s].defined[name]
                if typ == "STT_FUNC":
                    return ("error", f"function {name} not declared in C")
                c = self.find_container(addr, seg)
                if c and c[0] != name:
                    inner = self.classify(c[0], seg)
                    if inner and inner[0] == "data":
                        return ("data+", inner[1], c[1])
                return ("error", f"symbol {name} not defined in C or generated data")
        if name in self.abs:
            return ("abs", self.abs[name])
        for s in SEGMENTS:
            if name in self.elves[s].absolute:
                return ("abs", self.elves[s].absolute[name])
        m = re.match(r"^D_([0-9A-F]{1,8})$", name)
        if m:
            return ("abs", int(m.group(1), 16))
        return None


def c_ident(name):
    return "g_" + name


class Emitter:
    def __init__(self, seg, syms, index, overrides):
        self.seg = seg
        self.syms = syms
        self.index = index
        self.overrides = overrides
        self.extern_decls = {}
        self.local = {}        # name -> Label emitted in this file
        self.counter = 0

    def ref_expr(self, sym, addend, label, off):
        """C expression (as u8 *) for relocation target, or None."""
        if sym in self.local:
            # forward references are common: always go through an extern alias of the asm name
            asm = self.syms.asm_name(sym, self.seg)
            ident = "d_" + asm
            self.extern_decls[ident] = f'extern u8 {ident}[] __asm__("{asm}");'
            return f"({ident} + {addend})" if addend else ident
        cls = self.syms.classify(sym, self.seg)
        if cls is None:
            REPORT.error(f"{label.name}+0x{off:X}: unresolved symbol {sym}")
            return "((u8 *)0)"
        if cls[0] == "error":
            REPORT.error(f"{label.name}+0x{off:X}: {cls[1]}")
            return "((u8 *)0)"
        if cls[0] == "abs":
            v = (cls[1] + addend) & 0xFFFFFFFF
            if 0x80000000 <= v < 0xA0000000:
                v &= 0x1FFFFFFF
            REPORT.note(f"{label.name}+0x{off:X}: absolute {sym} = 0x{v:08X}")
            return f"((u8 *)0x{v:08X}u)"
        if cls[0] == "func":
            asm, sig = cls[1], cls[2]
            ident = "f_" + asm
            ret, args, var = sig
            arglist = ", ".join(args) + (", ..." if var and args != ("void",) else "")
            self.extern_decls[ident] = f'extern {ret} {ident}({arglist}) __asm__("{asm}");'
            return f"((u8 *){ident} + {addend})" if addend else f"((u8 *){ident})"
        if cls[0] == "data+":
            asm, extra = cls[1], cls[2]
            addend += extra
            REPORT.note(f"{label.name}+0x{off:X}: {sym} -> {asm}+0x{extra:X}")
        else:
            asm = cls[1]
        ident = "d_" + asm
        self.extern_decls[ident] = f'extern u8 {ident}[] __asm__("{asm}");'
        base = ident
        return f"({base} + {addend})" if addend else base

    def type_for(self, label):
        ov = self.overrides.get(label.name)
        if ov is None:
            ov = self.overrides.get("@file:" + label.file)  # per-file layouts beat placeholder C types (u8 x;)
        if ov == "raw":
            return "raw"
        if ov is not None and ov.startswith("layout "):
            return ("layout", ov.split()[1:])
        if ov is not None:
            ti = flatten_override(ov)
            if ti is None:
                REPORT.error(f"{label.name}: data_types.txt type {ov!r} does not flatten")
            return ti
        return self.index.var_types.get(label.name)

    @staticmethod
    def layout_leaves(spec, n):
        """`layout` mini-language: iN (N-byte int), bN (N bytes), sN/s* (s16 x N / to the end), wN/w* (32-bit
        words), pN (pointers)."""
        leaves = []
        pos = 0
        for item in spec:
            kind, count = item[0], item[1:]
            width = {"i": None, "b": 1, "s": 2, "w": 4, "p": 4}[kind]
            if kind == "i":
                leaves.append((pos, int(count), "i"))
                pos += int(count)
                continue
            reps = (n - pos) // width if count == "*" else int(count)
            for _ in range(reps):
                if pos + width > n:
                    break
                leaves.append((pos, width, "p" if kind == "p" else "i"))
                pos += width
        return leaves

    @staticmethod
    def array_leaves(pattern, esz, base, n, total=None):
        """Leaves of an array of `esz`-byte elements (leaf `pattern`) that lie fully inside the window
        [base, base + n) of the array, rebased to the window; `total` bounds the array when known."""
        out = []
        first = base // esz
        end = base + n if total is None else min(base + n, total)
        i = first
        while i * esz < end:
            for o, s, k in pattern:
                a = i * esz + o
                if a >= base and a + s <= end:
                    out.append((a - base, s, k))
            i += 1
        return out

    def continuation_leaves(self, label):
        """Leaves for an untyped label that continues an array declared on an earlier label: splat cuts
        such arrays at every address other code references, leaving the tail without a C type."""
        cont = getattr(label, "cont", None)
        if cont is None:
            return None
        head, base = cont
        size, align, lv, elem = self.type_for(head)
        if size is None:
            return self.array_leaves(elem[2], elem[0], base, label.size)
        return [(o - base, s, k) for o, s, k in lv if o >= base and o + s <= base + label.size]

    def array_type_extent(self, label):
        """-> (bounded total or None) when `label`'s type is an array whose elements carry multi-byte or
        pointer leaves and that extends past the label; else False."""
        ti = self.type_for(label)
        if not isinstance(ti, tuple) or len(ti) != 4:
            return False
        size, align, lv, elem = ti
        if size is None and elem is not None and elem[0]:
            pattern = elem[2]
            if any(s > 1 or k[0] == "p" for _, s, k in pattern):
                return None
            return False
        if size is not None and size > label.size and lv and elem is not None:
            if any(s > 1 or k[0] == "p" for _, s, k in lv):
                return size
        return False

    def leaves_for(self, label):
        """-> list of (off, size, kind)."""
        n = label.size
        ti = self.type_for(label)
        leaves = []
        if ti == "raw":
            return [(o, 1, "i") for o in range(n)]
        if isinstance(ti, tuple) and ti and ti[0] == "layout":
            return self.apply_relocs(label, sorted(self.layout_leaves(ti[1], n)))
        if ti is None:
            cl = self.continuation_leaves(label)
            if cl is not None:
                REPORT.note(f"{label.name}: continues the array {label.cont[0].name} at +0x{label.cont[1]:X}")
                ti = (n, 1, cl, None)
        if ti is not None:
            size, align, lv, elem = ti
            if size is None and elem is not None:
                esz = elem[0]
                if esz and esz > 0:
                    lv = self.array_leaves(elem[2], esz, 0, n)
                    size = n
                else:
                    lv, size = None, 0
            if lv is not None:
                if size > n:
                    REPORT.note(f"{label.name}: type size 0x{size:X} > label size 0x{n:X}, truncated")
                leaves = [l for l in lv if l[0] + l[1] <= n]
                covered = min(size, n)
            else:
                covered = 0
        else:
            covered = 0
        if ti is None:
            REPORT.note(f"{label.name}: no C type, using directive widths")
        elif covered < n and label.kind != "bss":
            tail = label.data[covered:n]
            if any(tail):
                REPORT.note(f"{label.name}: 0x{n - covered:X} bytes past sizeof(T) use directive widths")
        # fill the rest from directive widths
        pos = covered
        if ti is None:
            pos = 0
        while pos < n:
            w = label.widths.get(pos)
            if w and pos + w <= n:
                kind = "p" if pos in label.relocs else "i"
                leaves.append((pos, w, kind))
                pos += w
            else:
                leaves.append((pos, 1, "i"))
                pos += 1
        leaves.sort()
        # struct padding and other holes between typed leaves keep their raw bytes
        filled = []
        pos = 0
        for lo, ls, lk in leaves:
            if lo < pos:
                REPORT.error(f"{label.name}+0x{lo:X}: overlapping leaves")
                continue
            filled.extend((b, 1, "i") for b in range(pos, lo))
            filled.append((lo, ls, lk))
            pos = lo + ls
        filled.extend((b, 1, "i") for b in range(pos, n))
        return self.apply_relocs(label, self.promote_pointer_bytes(label, filled))

    def promote_pointer_bytes(self, label, leaves):
        """spimdisasm emits `.byte` for data it saw byte loads on, dropping relocations of pointers stored
        there. A word-aligned run of four byte leaves whose value is exactly the start of a known function
        or data symbol is taken as such a pointer."""
        if label.kind == "bss" or label.file.startswith("shadow:"):
            return leaves
        out = []
        i = 0
        while i < len(leaves):
            off, size, kind = leaves[i]
            if (size == 1 and (label.vram + off) % 4 == 0 and i + 3 < len(leaves)
                    and all(leaves[i + k][:2] == (off + k, 1) for k in range(4))
                    and not any(off + k in label.relocs for k in range(4))):
                val = int.from_bytes(label.data[off:off + 4], "big")
                target = None
                if 0x80000400 <= val < 0x80800000 and val % 4 == 0:
                    target = self.syms.func_at(val, self.seg)
                    if target is None:
                        c = self.syms.find_container(val, self.seg)
                        if c is not None and c[1] == 0:
                            cls = self.syms.classify(c[0], self.seg)
                            if cls and cls[0] in ("data", "data+"):
                                target = c[0]
                if target is not None:
                    REPORT.note(f"{label.name}+0x{off:X}: bytes 0x{val:08X} promoted to a pointer to {target}")
                    out.append((off, 4, "p"))
                    i += 4
                    continue
            out.append((off, size, kind))
            i += 1
        return out

    def apply_relocs(self, label, leaves):
        """Drop relocations to non-RDRAM absolute symbols (spimdisasm-symbolized constants) and make
        every remaining relocation a 4-byte pointer leaf, splitting typed leaves it overlaps."""
        for ro, (sym, addend) in list(label.relocs.items()):
            if sym in self.local:
                continue
            cls = self.syms.classify(sym, self.seg)
            if cls is not None and cls[0] == "abs" and not (0x80000000 <= cls[1] < 0xA0000000):
                del label.relocs[ro]
        by_off = {l[0]: l for l in leaves}
        for ro in sorted(label.relocs):
            if ro in by_off and by_off[ro][1] == 4:
                continue
            REPORT.note(f"{label.name}+0x{ro:X}: relocation overrides typed leaves")
            out = []
            for lo, ls, lk in leaves:
                if lo + ls <= ro or lo >= ro + 4:
                    out.append((lo, ls, lk))
                    continue
                for b in range(lo, lo + ls):
                    if not ro <= b < ro + 4:
                        out.append((b, 1, "i"))
            out.append((ro, 4, "p"))
            leaves = sorted(out)
            by_off = {l[0]: l for l in leaves}
        return leaves


    def emit_label(self, label, out):
        self._emit_def(label, out)
        target = self.syms.asm_name(label.name, self.seg)
        for a in label.aliases:
            out.append(f'extern u8 alias_{a}[] __asm__("{a}") __attribute__((alias("{target}")));')

    def _emit_def(self, label, out):
        n = label.size
        attrs_align = 1
        v = label.vram
        while attrs_align < 16 and v % (attrs_align * 2) == 0:
            attrs_align *= 2
        if label.kind == "bss" or (not any(label.data) and not label.relocs):
            sect = "bss" if label.kind == "bss" else "data"
            out.append(f"/* {label.name} @ 0x{label.vram:08X} size 0x{n:X} */")
            out.append(f'__attribute__((used, aligned({attrs_align}))) u8 {c_ident(label.name)}[{max(n, 1)}] '
                       f'__asm__("{self.syms.asm_name(label.name, self.seg)}") = {{0}};')
            return
        leaves = self.leaves_for(label)
        fields = []
        inits = []
        reloc_used = set()
        i = 0
        fid = 0

        def be(off, size):
            return int.from_bytes(label.data[off:off + size], "big")

        while i < len(leaves):
            off, size, kind = leaves[i]
            reloc = label.relocs.get(off)
            if reloc is not None and size == 4:
                reloc_used.add(off)
                expr = self.ref_expr(reloc[0], reloc[1], label, off)
                if kind[0] == "p":
                    fields.append(f"void *f{fid};")
                    inits.append(f"(void *){expr}")
                else:
                    REPORT.note(f"{label.name}+0x{off:X}: relocation {reloc[0]} on integer leaf")
                    fields.append(f"u32 f{fid};")
                    inits.append(f"(u32){expr}")
                fid += 1
                i += 1
                continue
            if kind[0] == "p" and size == 4:
                val = be(off, 4)
                if val == 0:
                    fields.append(f"void *f{fid};")
                    inits.append("0")
                else:
                    if self.seg not in OVERLAYS and OVL_VRAM[0] <= val < OVL_VRAM[1]:
                        disp = self.syms.overlay_fn_dispatcher(val)
                        if disp is not None:
                            name, (ret, args, _var) = disp
                            self.extern_decls[name] = f"extern {ret} {name}({', '.join(args)});"
                            fields.append(f"void *f{fid};")
                            inits.append(f"(void *){name}")
                            REPORT.note(f"{label.name}+0x{off:X}: overlay function 0x{val:08X} -> {name}")
                            fid += 1
                            i += 1
                            continue
                    fn = self.syms.func_at(val, self.seg)
                    if fn is not None:
                        expr = self.ref_expr(fn, 0, label, off)
                        fields.append(f"void *f{fid};")
                        inits.append(f"(void *){expr}")
                        REPORT.note(f"{label.name}+0x{off:X}: function pointer 0x{val:08X} -> {fn} (no reloc)")
                        fid += 1
                        i += 1
                        continue
                    c = self.syms.find_container(val, self.seg) if 0x80000000 <= val < 0x80800000 else None
                    if c is not None:
                        cls = self.syms.classify(c[0], self.seg)
                        if cls and cls[0] in ("data", "func"):
                            expr = self.ref_expr(c[0], c[1], label, off)
                            fields.append(f"void *f{fid};")
                            inits.append(f"(void *){expr}")
                            REPORT.note(f"{label.name}+0x{off:X}: pointer 0x{val:08X} -> {c[0]}+0x{c[1]:X} (no reloc)")
                            fid += 1
                            i += 1
                            continue
                    hv = val & 0x1FFFFFFF if 0x80000000 <= val < 0xA0000000 else val
                    REPORT.note(f"{label.name}+0x{off:X}: pointer leaf 0x{val:08X} without symbol -> 0x{hv:08X}")
                    fields.append(f"void *f{fid};")
                    inits.append(f"(void *)0x{hv:08X}u")
                fid += 1
                i += 1
                continue
            # run of same-size integer leaves, contiguous, no relocs
            j = i
            vals = []
            while j < len(leaves):
                o2, s2, k2 = leaves[j]
                if j > i and (s2 != size or o2 != off + (j - i) * size or (o2 in label.relocs) or (k2[0] == "p" and s2 == 4)):
                    break
                vals.append(be(o2, s2))
                if (label.vram + o2) % 4 == 0 and o2 + 4 <= n and s2 in (1, 4):
                    w = be(o2, 4)
                    fn = self.syms.func_at(w, self.seg) if 0x80000400 <= w < 0x80800000 and w % 4 == 0 else None
                    if fn is not None:
                        REPORT.note(f"SUSPECT: {label.name}+0x{o2:X}: integer data 0x{w:08X} is the address of {fn}")
                j += 1
            ctype = {1: "u8", 2: "u16", 4: "u32", 8: "u64"}[size]
            suffix = {1: "", 2: "", 4: "u", 8: "ull"}[size]
            if len(vals) == 1:
                fields.append(f"{ctype} f{fid};")
                inits.append(f"0x{vals[0]:X}{suffix}")
            else:
                fields.append(f"{ctype} f{fid}[{len(vals)}];")
                inits.append("{" + ",".join(f"0x{x:X}{suffix}" for x in vals) + "}")
            fid += 1
            i = j
        for ro in label.relocs:
            if ro not in reloc_used:
                REPORT.error(f"{label.name}+0x{ro:X}: relocation {label.relocs[ro][0]} not on a 4-byte leaf")
        out.append(f"/* {label.name} @ 0x{label.vram:08X} size 0x{n:X} */")
        out.append(f"__attribute__((used, aligned({attrs_align}))) struct __attribute__((packed)) {{ "
                   + " ".join(fields) + f" }} {c_ident(label.name)} "
                   f'__asm__("{self.syms.asm_name(label.name, self.seg)}") = {{ ' + ", ".join(inits) + " };")

    def mark_continuations(self, labels):
        """Registers `labels` as local and sets `label.cont` on untyped labels that continue a typed array
        declared on an earlier label of the same file. -> labels grouped by file, each sorted by vram."""
        by_file = defaultdict(list)
        for l in labels:
            by_file[l.file].append(l)
            self.local[l.name] = l
        for file, ls in by_file.items():
            ls.sort(key=lambda l: l.vram)
            head = None
            for l in ls:
                l.cont = None
                if self.type_for(l) is not None:
                    ext = self.array_type_extent(l)
                    head = None if ext is False else (l, ext)
                elif head is not None and (head[1] is None or l.vram - head[0].vram < head[1]):
                    # an unbounded ([]) array only claims followers spimdisasm emitted as plain bytes (it
                    # had no view of them); followers with their own words/relocs are separate data
                    if head[1] is None and (l.relocs or any(w != 1 for w in l.widths.values())):
                        head = None
                    else:
                        l.cont = (head[0], l.vram - head[0].vram)
                else:
                    head = None
        return by_file

    def emit(self, labels):
        body = []
        by_file = self.mark_continuations(labels)
        for file, ls in by_file.items():
            sect_kind = "bss" if all(l.kind == "bss" for l in ls) else "data"
            tag = re.sub(r"\W", "_", file)
            body.append(f"\n/* ---- {file} ---- */")
            body.append(f'#pragma clang attribute push (__attribute__((section(".{sect_kind}.dkgen_{tag}"))), apply_to = variable(is_global))')
            lead = ls[0].vram % 16
            if lead:
                body.append(f"__attribute__((used, aligned(16))) u8 lead_{tag}[{lead}] = {{0}};")
            for l in ls:
                if sect_kind == "bss" and l.kind != "bss":
                    REPORT.error(f"{file}: mixed bss and data")
                self.emit_label(l, body)
            body.append("#pragma clang attribute pop")
        head = [f"/* generated by tools/gen_data.py: segment {self.seg}; do not edit */",
                '#include "port/port.h"', ""]
        head += sorted(self.extern_decls.values())
        return "\n".join(head + body) + "\n"


def gen_layout_check(per_seg, syms):
    lines = ["/* generated by tools/gen_data.py */", '#include "port/port.h"',
             "#include <stdio.h>", "#include <stdlib.h>", ""]
    decls = set()
    checks = []
    total = 0
    for seg, labels in per_seg.items():
        by_file = defaultdict(list)
        for l in labels:
            by_file[l.file].append(l)
        for file, ls in by_file.items():
            ls.sort(key=lambda l: l.vram)
            total += len(ls)
            for a, b in zip(ls, ls[1:]):
                an, bn = syms.asm_name(a.name, seg), syms.asm_name(b.name, seg)
                decls.add(f'extern u8 c_{an}[] __asm__("{an}");')
                decls.add(f'extern u8 c_{bn}[] __asm__("{bn}");')
                checks.append(f'    if ((u32)c_{bn} - (u32)c_{an} != 0x{b.vram - a.vram:X}u) fail("{a.name}/{b.name}");')
    lines += sorted(decls)
    lines += ["", "static void fail(const char *what) {",
              '    printf("PORT: generated data layout broken at %s\\n", what);', "    abort();", "}", "",
              "void portGenLayoutCheck(void) {"]
    lines += checks
    lines += [f'    printf("PORT: layout ok %d labels\\n", {total});', "}"]
    write_if_changed(GEN / "gen_layout_check.c", "\n".join(lines) + "\n")


def gen_rom_layout(abs_syms):
    order = ["boot", "global", "multiplayer", "minecart", "bonus", "race", "critter", "boss", "arcade",
             "jetpac", "menu", "seg11", "seg12", "seg13", "seg14", "seg15", "seg16", "seg17"]
    rows = []
    for n in order:
        s, e = abs_syms.get(f"{n}_ROM_START"), abs_syms.get(f"{n}_ROM_END")
        if s is None or e is None:
            REPORT.error(f"rom layout: missing {n}_ROM_START/END")
            s = e = 0
        rows.append(f"    {{ 0x{s:08X}u, 0x{e:08X}u }}, /* {n} */")
    text = "\n".join(["/* generated by tools/gen_data.py (order of src/boot/main.c SEG()) */",
                      '#include "port/port.h"', "", "const u32 gPortSegRom[18][2] = {"] + rows + ["};"]) + "\n"
    write_if_changed(GEN / "rom_layout.c", text)


OVL_IDS = {"menu": 2, "multiplayer": 3, "minecart": 4, "race": 5, "critter": 6, "boss": 7, "bonus": 8,
           "arcade": 9, "jetpac": 10}


def gen_ovl_entry(elves, syms, index):
    entries = {}
    for ovl in ("arcade", "jetpac"):
        for n, (addr, size, typ) in elves[ovl].defined.items():
            if addr == 0x80024000 and typ == "STT_FUNC":
                entries[ovl] = syms.asm_name(n, ovl)
    lines = ["/* generated by tools/gen_data.py */", '#include "port/port.h"', "#include <stdio.h>",
             "#include <stdlib.h>", "", "extern int gPortCurrentOverlay;"]
    for ovl, fn in entries.items():
        lines.append(f'extern void ovl_{ovl}_entry(void) __asm__("{fn}");')
    lines += ["", "void portOverlayEntry(void) {", "    switch (gPortCurrentOverlay) {"]
    for ovl in entries:
        lines.append(f"    case {OVL_IDS[ovl]}: ovl_{ovl}_entry(); return;")
    lines += ['    default: printf("PORT: overlay entry with overlay %d\\n", gPortCurrentOverlay); abort();',
              "    }", "}"]
    # Non-overlay code calls overlay functions by their VRAM (func_800XXXXX declared, never defined in C):
    # dispatch to whichever overlay is active.
    for name in sorted(index.func):
        m = re.match(r"^func_(800[2-4][0-9A-F]{4})$", name)
        if not m or name in index.func_defined:
            continue
        addr = int(m.group(1), 16)
        if addr == 0x80024000:
            continue
        targets = []
        for ovl in OVERLAYS:
            for n, (a, size, typ) in elves[ovl].defined.items():
                if a == addr and typ == "STT_FUNC" and n in index.func_defined:
                    targets.append((ovl, syms.asm_name(n, ovl), n))
        if not targets:
            REPORT.error(f"overlay dispatcher {name}: no overlay defines a function at 0x{addr:08X}")
            continue
        sigs = {index.func.get(n) for _, _, n in targets}
        if len(sigs) != 1 or None in sigs:
            REPORT.error(f"overlay dispatcher {name}: targets disagree on their signature {sigs}")
            continue
        ret, args, var = sigs.pop()
        if index.func.get(name) != (ret, args, var):
            REPORT.note(f"overlay dispatcher {name}: callers declare {index.func.get(name)}, target is {(ret, args, var)}")
        targets = [(o, fn) for o, fn, _ in targets]
        params = [] if args == ("void",) else [f"{t} a{i}" for i, t in enumerate(args)]
        call_args = ", ".join(f"a{i}" for i in range(len(params)))
        decl_params = ", ".join(params) or "void"
        lines.append("")
        for ovl, fn in targets:
            lines.append(f'extern {ret} ovl_{ovl}_{name}({", ".join(args)}) __asm__("{fn}");')
        lines.append(f"{ret} {name}({decl_params}) {{")
        lines.append("    switch (gPortCurrentOverlay) {")
        for ovl, fn in targets:
            ret_kw = "return " if ret != "void" else ""
            tail = "" if ret != "void" else " return;"
            lines.append(f"    case {OVL_IDS[ovl]}: {ret_kw}ovl_{ovl}_{name}({call_args});{tail}")
        lines.append(f'    default: printf("PORT: {name} called with overlay %d\\n", gPortCurrentOverlay); abort();')
        lines += ["    }", "}"]
        REPORT.note(f"overlay dispatcher {name}: {', '.join(o for o, _ in targets)}")
    # thunks for pointers to overlay functions stored in global/boot data (no relocation in the N64 data)
    for addr in sorted(syms.ovl_fn_ptrs):
        ret, args, _var = syms.ovl_fn_sigs[addr]
        name = f"port_ovlfn_{addr:08X}"
        params = [] if args == ("void",) else [f"{t} a{i}" for i, t in enumerate(args)]
        lines.append("")
        for ovl, n in syms.ovl_fn_ptrs[addr]:
            tret, targs, _ = index.func[n]
            lines.append(f'extern {tret} ovlfn_{ovl}_{addr:08X}({", ".join(targs)}) __asm__("{syms.asm_name(n, ovl)}");')
        lines.append(f"{ret} {name}({', '.join(params) or 'void'}) {{")
        lines.append("    switch (gPortCurrentOverlay) {")
        for ovl, n in syms.ovl_fn_ptrs[addr]:
            tret, targs, _ = index.func[n]
            nargs = 0 if targs == ("void",) else len(targs)
            call_args = ", ".join(f"a{i}" if i < len(params) else "0" for i in range(nargs))
            call = f"ovlfn_{ovl}_{addr:08X}({call_args})"
            if ret == "void":
                lines.append(f"    case {OVL_IDS[ovl]}: {call}; return;")
            elif tret == "void":
                lines.append(f"    case {OVL_IDS[ovl]}: {call}; return 0;")
            else:
                lines.append(f"    case {OVL_IDS[ovl]}: return ({ret}){call};")
        lines.append(f'    default: printf("PORT: overlay function 0x{addr:08X} called with overlay %d\\n", '
                     f'gPortCurrentOverlay); abort();')
        lines += ["    }", "}"]
    write_if_changed(GEN / "ovl_entry.c", "\n".join(lines) + "\n")


def infer_pointee_types(per_seg, syms, index, overrides):
    """Untyped labels that a typed pointer points at (addend 0) take the pointee type, as an array filling
    the label (e.g. `u16 *D_8074E218[]` types each list it points at as u16[]). Repeats to a fixpoint."""
    by_name = {l.name: l for ls in per_seg.values() for l in ls}
    for _ in range(8):
        found = {}
        for seg, labels in per_seg.items():
            em = Emitter(seg, syms, index, overrides)
            # continuation labels carry their head array's element types, so their pointers type pointees too
            em.mark_continuations(labels)
            for l in labels:
                if l.kind == "bss" or (em.type_for(l) is None and l.cont is None):
                    continue
                for off, size, kind in em.leaves_for(l):
                    if not kind.startswith("p|") or size != 4:
                        continue
                    if off in l.relocs:
                        sym, addend = l.relocs[off]
                    else:
                        # N64 data pointers often carry no relocation; resolve the raw value like _emit_def does
                        val = int.from_bytes(l.data[off:off + 4], "big")
                        c = syms.find_container(val, seg) if 0x80000000 <= val < 0x80800000 else None
                        if c is None:
                            continue
                        sym, addend = c[0], c[1]
                    target = by_name.get(sym)
                    if addend != 0 or target is None or target.kind == "bss":
                        continue
                    if index.var_types.get(sym) is not None or sym in overrides:
                        continue
                    pointee = index.pointee_types.get(kind[2:])
                    if pointee is None or pointee[0] is None or pointee[0] <= 0:
                        continue
                    prev = found.get(sym)
                    if prev is not None and prev[0] != kind[2:]:
                        REPORT.note(f"{sym}: pointed at as {prev[0]} and {kind[2:]}; keeping the first")
                        continue
                    found[sym] = (kind[2:], pointee)
        if not found:
            return
        for sym, (spelling, pointee) in found.items():
            index.var_types[sym] = (None, pointee[1], None, pointee)
            REPORT.note(f"{sym}: typed as {spelling}[] from a typed pointer to it")

def run_full(elves):
    sys.setrecursionlimit(10000)
    index = Index().build()
    per_seg = collect_labels(index, elves)
    clashes = overlay_clashes(elves)
    abs_syms = abs_symbols(elves)
    syms = Symbols(elves, index, per_seg, clashes, abs_syms)
    overrides = load_data_types()
    infer_pointee_types(per_seg, syms, index, overrides)
    for seg in SEGMENTS:
        em = Emitter(seg, syms, index, overrides)
        text = em.emit(per_seg[seg])
        write_if_changed(GEN / f"data_{seg}.c", text)
    gen_layout_check(per_seg, syms)
    gen_rom_layout(abs_syms)
    gen_ovl_entry(elves, syms, index)
    n = sum(len(v) for v in per_seg.values())
    REPORT.note(f"total labels: {n}")
    report_unresolved(index, per_seg, syms)
    (GEN / "report.txt").write_text("\n".join(REPORT.lines) + "\n")
    print(f"gen: {n} labels, {REPORT.errors} errors (build/gen/report.txt)")
    return 1 if REPORT.errors else 0


def report_unresolved(index, per_seg, syms):
    """C-declared variables defined by neither C nor generated data: interior labels of C objects
    (fix by patch: #define X (*(T *)((u8 *)&PARENT + OFF))) or absolute symbols (PORT_ABS_X)."""
    generated = {l.name for ls in per_seg.values() for l in ls}
    for name in sorted(index.declared - set(index.c_defined) - generated):
        for seg in SEGMENTS:
            if name in syms.elves[seg].defined:
                addr = syms.elves[seg].defined[name][0]
                c = syms.find_container(addr, seg)
                if c is not None and c[0] != name:
                    REPORT.note(f"UNRESOLVED {name}: interior of {c[0]}+0x{c[1]:X} ({'C' if c[0] in index.c_defined else 'generated'})")
                else:
                    REPORT.note(f"UNRESOLVED {name}: defined at 0x{addr:08X} in {seg}, no containing object")
                break
        else:
            if name in syms.abs:
                v = syms.abs[name]
                c = None
                for seg in SEGMENTS:
                    c = c or (syms.find_container(v, seg) if 0x80000000 <= v < 0x80800000 else None)
                where = f", interior of {c[0]}+0x{c[1]:X}" if c else ""
                REPORT.note(f"UNRESOLVED {name}: absolute 0x{v:08X} (PORT_ABS_{name}){where}")


