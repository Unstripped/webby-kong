def game_sources():
    src = TREE / "src"
    files = sorted((src / "global").glob("*.c"))
    files += [src / "boot" / f"{n}.c" for n in ("1CC0", "30E0", "3630", "3D20", "6690")]
    files += sorted((src / "boot/libultra/gu").glob("*.c")) + sorted((src / "boot/libultra/mgu").glob("*.c"))
    files += [src / "boot/libultra/libc/ll.c", src / "boot/libultra/libc/llcvt.c"]
    for o in OVERLAYS:
        files += sorted((src / o).glob("*.c"))
    return files


def seg_of_source(path: Path):
    rel = path.relative_to(TREE / "src").parts[0]
    return rel if rel in OVERLAYS else ("boot" if rel == "boot" else "global")


_TYPE_CACHE = {}
_PENDING_POINTEES = []


def flatten_type(t, report):
    """-> (size, align, leaves[(off, size, kind)], elem) ; kind in i/f/p ; None if incomplete."""
    import clang.cindex as ci
    t = t.get_canonical()
    key = t.spelling
    if key in _TYPE_CACHE:
        return _TYPE_CACHE[key]
    _TYPE_CACHE[key] = None  # in progress: self-referential pointers resolve later through _PENDING_POINTEES
    K = ci.TypeKind
    k = t.kind
    res = None
    if k in (K.POINTER, K.BLOCKPOINTER):
        pointee = t.get_pointee().get_canonical()
        if pointee.kind in (K.VOID, K.FUNCTIONPROTO, K.FUNCTIONNOPROTO, K.INVALID):
            res = (4, 4, [(0, 4, "p")], None)
        else:
            # "p|<pointee>": lets the generator type untyped labels that typed pointers point at
            _PENDING_POINTEES.append(pointee)
            res = (4, 4, [(0, 4, "p|" + pointee.spelling)], None)
    elif k in (K.CHAR_S, K.SCHAR, K.CHAR_U, K.UCHAR, K.BOOL):
        res = (1, 1, [(0, 1, "i")], None)
    elif k in (K.SHORT, K.USHORT):
        res = (2, 2, [(0, 2, "i")], None)
    elif k in (K.INT, K.UINT, K.LONG, K.ULONG, K.ENUM):
        sz = t.get_size()
        res = (sz, sz, [(0, sz, "i")], None)
    elif k in (K.LONGLONG, K.ULONGLONG):
        res = (8, 8, [(0, 8, "i")], None)
    elif k == K.FLOAT:
        res = (4, 4, [(0, 4, "f")], None)
    elif k == K.DOUBLE:
        res = (8, 8, [(0, 8, "f")], None)
    elif k == K.CONSTANTARRAY:
        el = flatten_type(t.element_type, report)
        if el is not None:
            n = t.element_count
            leaves = []
            for i in range(n):
                base = i * el[0]
                leaves.extend((base + o, s, kk) for o, s, kk in el[2])
            res = (el[0] * n, el[1], leaves, el)  # elem: lets labels splat cut off its tail continue it
    elif k == K.INCOMPLETEARRAY:
        el = flatten_type(t.element_type, report)
        if el is not None:
            res = (None, el[1], None, el)
    elif k == K.RECORD:
        sz = t.get_size()
        if sz > 0:
            decl = t.get_declaration()
            fields = list(t.get_fields())
            if decl.kind == ci.CursorKind.UNION_DECL:
                best = None
                for f in fields:
                    if f.is_bitfield():
                        continue
                    ft = flatten_type(f.type, report)
                    if ft is None or ft[0] is None:
                        continue
                    if best is None or ft[0] > best[1][0]:
                        best = (f, ft)
                if best is not None:
                    if len(fields) > 1:
                        report.note(f"union {key}: using member {best[0].spelling}")
                    res = (sz, t.get_align(), list(best[1][2]), None)
            else:
                leaves = []
                ok = True
                for f in fields:
                    if f.is_bitfield():
                        report.note(f"bitfield in {key}.{f.spelling}")
                        ok = False
                        break
                    ft = flatten_type(f.type, report)
                    if ft is None or ft[0] is None:
                        ok = False
                        break
                    base = f.get_field_offsetof() // 8
                    leaves.extend((base + o, s, kk) for o, s, kk in ft[2])
                if ok:
                    res = (sz, t.get_align(), leaves, None)
    _TYPE_CACHE[key] = res
    return res


def lower_scalar(t):
    import clang.cindex as ci
    K = ci.TypeKind
    t = t.get_canonical()
    k = t.kind
    if k == K.VOID:
        return "void"
    if k in (K.POINTER, K.BLOCKPOINTER, K.CONSTANTARRAY, K.INCOMPLETEARRAY):
        return "void *"
    if k == K.FLOAT:
        return "float"
    if k == K.DOUBLE:
        return "double"
    if k in (K.LONGLONG, K.ULONGLONG):
        return "long long"
    if k in (K.CHAR_S, K.SCHAR, K.CHAR_U, K.UCHAR, K.BOOL, K.SHORT, K.USHORT, K.INT, K.UINT, K.LONG, K.ULONG, K.ENUM):
        return "int"
    return None


def lower_function(t):
    import clang.cindex as ci
    t = t.get_canonical()
    ret = lower_scalar(t.get_result())
    if ret is None:
        return None
    if t.kind == ci.TypeKind.FUNCTIONNOPROTO:
        return (ret, ("void",), False)
    args = []
    for a in t.argument_types():
        la = lower_scalar(a)
        if la is None:
            return None
        args.append(la)
    return (ret, tuple(args) or ("void",), t.is_function_variadic())


def index_tu(path_str):
    """Parse one TU; return its file-scope variables and functions."""
    import clang.cindex as ci
    path = Path(path_str)
    rep = Report()
    args = game_flags()
    seg = seg_of_source(path)
    if seg in OVERLAYS:
        args = args + ["-include", str(GEN / "include" / "ovl" / f"{seg}.h")]
    idx = ci.Index.create()
    tu = idx.parse(str(path), args=args)  # bodies needed: is_definition() is False when they are skipped
    errs = [d for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
    if errs:
        rep.error(f"libclang {path.name}: {errs[0]}")
    vars_ = []   # (name, defined, static, typeinfo)
    funcs = []   # (name, defined, static, sig)
    for c in tu.cursor.get_children():
        if c.kind == ci.CursorKind.VAR_DECL:
            static = c.storage_class == ci.StorageClass.STATIC
            extern = c.storage_class == ci.StorageClass.EXTERN
            ti = flatten_type(c.type, rep)
            vars_.append((c.spelling, not extern, static, ti))
        elif c.kind == ci.CursorKind.FUNCTION_DECL:
            static = c.storage_class == ci.StorageClass.STATIC
            funcs.append((c.spelling, c.is_definition(), static, lower_function(c.type)))
    pointees = {}
    while _PENDING_POINTEES:
        pt = _PENDING_POINTEES.pop()
        if pt.spelling not in pointees:
            pointees[pt.spelling] = flatten_type(pt, rep)
    return seg, vars_, funcs, rep.lines, pointees


class Index:
    def __init__(self):
        self.var_types = {}          # name -> typeinfo (first complete)
        self.c_defined = {}          # name -> (seg, static)
        self.func = {}               # name -> sig (definition preferred)
        self.func_defined = {}       # name -> (seg, static)
        self.declared = set()        # every file-scope variable name C declares
        self.pointee_types = {}      # pointee type spelling -> typeinfo (for typing untyped pointer targets)

    def build(self):
        files = [str(p) for p in game_sources()]
        with ProcessPoolExecutor(max_workers=os.cpu_count()) as ex:
            results = list(ex.map(index_tu, files, chunksize=4))
        for seg, vars_, funcs, lines, pointees in results:
            for sp, ti in pointees.items():
                if ti is not None and sp not in self.pointee_types:
                    self.pointee_types[sp] = ti
            for line in lines:
                if line.startswith("ERROR: "):
                    REPORT.error(line[7:])
                else:
                    REPORT.note(line)
            for name, defined, static, ti in vars_:
                self.declared.add(name)
                if defined:
                    self.c_defined.setdefault(name, (seg, static))
                if ti is not None and name not in self.var_types:
                    if ti[0] is not None or ti[3] is not None:
                        self.var_types[name] = ti
            for name, defined, static, sig in funcs:
                if defined:
                    self.func_defined[name] = (seg, static)
                    if sig is not None:
                        self.func[name] = sig
                elif sig is not None and name not in self.func:
                    self.func[name] = sig
        return self


# ----------------------------------------------------------------------------- asm data parsing

class Label:
    def __init__(self, name, vram, seg, file, kind):
        self.name = name
        self.vram = vram
        self.seg = seg
        self.file = file
        self.kind = kind       # data / rodata / bss
        self.data = bytearray()
        self.relocs = {}       # offset -> symbol name
        self.widths = {}       # offset -> directive width (1/2/4/8, or 'w' for word)
        self.aliases = []      # other names for this exact address
        self.size = 0

    def put(self, off, b):
        end = off + len(b)
        if len(self.data) < end:
            self.data.extend(b"\0" * (end - len(self.data)))
        self.data[off:end] = b


LINE_RE = re.compile(r"^\s*/\*\s*([0-9A-Fa-f ]+?)\s*\*/\s*\.(\w+)\s*(.*?)\s*(?:/\*.*\*/)?\s*$")
LABEL_RE = re.compile(r"^\s*(?:dlabel|glabel)\s+([A-Za-z_.$][\w.$]*)")
SECTION_RE = re.compile(r"^\s*\.section\s+\.?(\w+)")


def unescape(s):
    out = bytearray()
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == "\\":
            i += 1
            e = s[i]
            if e in "01234567":
                j = i
                while j < len(s) and j < i + 3 and s[j] in "01234567":
                    j += 1
                out.append(int(s[i:j], 8) & 0xFF)
                i = j
                continue
            if e == "x":
                j = i + 1
                while j < len(s) and s[j] in "0123456789abcdefABCDEF":
                    j += 1
                out.append(int(s[i + 1:j], 16) & 0xFF)
                i = j
                continue
            out.append({"n": 10, "t": 9, "r": 13, "\\": 92, '"': 34, "'": 39, "a": 7, "b": 8, "f": 12, "v": 11}[e])
            i += 1
            continue
        out.extend(ch.encode("latin-1"))
        i += 1
    return bytes(out)


def parse_int(tok):
    tok = tok.strip()
    neg = tok.startswith("-")
    v = int(tok.lstrip("-"), 0)
    return -v if neg else v


def parse_asm_file(path: Path, seg):
    rel = str(path.relative_to(DECOMP))
    kind_default = "data"
    for k in ("rodata", "bss", "data"):
        if path.name.endswith(f".{k}.s"):
            kind_default = k
            break
    labels = []
    cur = None
    kind = kind_default
    for raw in path.read_text().splitlines():
        m = SECTION_RE.match(raw)
        if m:
            kind = {"rodata": "rodata", "bss": "bss", "late_rodata": "rodata"}.get(m.group(1), "data")
            continue
        m = LABEL_RE.match(raw)
        if m:
            cur = None
            name = m.group(1)
            cur = Label(name, None, seg, rel, kind)
            labels.append(cur)
            continue
        m = LINE_RE.match(raw)
        if not m or cur is None:
            continue
        toks = m.group(1).split()
        op, arg = m.group(2), m.group(3)
        if len(toks) == 1:
            vram, blob = int(toks[0], 16), None
        else:
            vram = int(toks[1], 16)
            blob = bytes.fromhex(toks[2]) if len(toks) > 2 else None
        if cur.vram is None:
            cur.vram = vram
        off = vram - cur.vram
        if op == "word":
            a = arg.strip()
            if re.match(r"^-?(0x[0-9A-Fa-f]+|\d+)$", a):
                cur.put(off, struct.pack(">I", parse_int(a) & 0xFFFFFFFF))
            else:
                m2 = re.match(r"^([A-Za-z_.$][\w.$]*)\s*(?:([+-])\s*(0x[0-9A-Fa-f]+|\d+))?$", a)
                if not m2:
                    REPORT.error(f"{rel}: cannot parse .word {a}")
                    continue
                sym = m2.group(1)
                addend = int(m2.group(3), 0) * (-1 if m2.group(2) == "-" else 1) if m2.group(3) else 0
                cur.put(off, blob if blob and len(blob) == 4 else b"\0\0\0\0")
                if sym.startswith(".L"):
                    REPORT.note(f"{cur.name}+0x{off:X}: code label {sym} emitted as 0")
                    cur.put(off, b"\0\0\0\0")
                else:
                    cur.relocs[off] = (sym, addend)
            cur.widths[off] = 4
        elif op in ("short", "half", "hword"):
            cur.put(off, struct.pack(">H", parse_int(arg) & 0xFFFF))
            cur.widths[off] = 2
        elif op == "byte":
            cur.put(off, bytes([parse_int(arg) & 0xFF]))
            cur.widths[off] = 1
        elif op == "float":
            cur.put(off, blob if blob and len(blob) == 4 else struct.pack(">f", float(arg)))
            cur.widths[off] = 4
        elif op == "double":
            cur.put(off, blob if blob and len(blob) == 8 else struct.pack(">d", float(arg)))
            cur.widths[off] = 8
        elif op == "space":
            n = parse_int(arg)
            cur.put(off, b"\0" * n)
        elif op in ("asciz", "ascii"):
            s = unescape(arg.strip()[1:-1])
            if op == "asciz":
                s += b"\0"
            cur.put(off, s)
        else:
            REPORT.error(f"{rel}: unknown directive .{op}")
    labels = [l for l in labels if l.vram is not None]
    for a, b in zip(labels, labels[1:]):
        if b.vram < a.vram + len(a.data):
            REPORT.error(f"{rel}: labels {a.name}/{b.name} overlap")
        a.size = b.vram - a.vram
    if labels:
        labels[-1].size = len(labels[-1].data)
        if labels[-1].kind == "bss":
            labels[-1].size = len(labels[-1].data)
    for l in labels:
        if len(l.data) < l.size:
            l.data.extend(b"\0" * (l.size - len(l.data)))
    return labels


def symbol_addrs():
    out = {}
    for line in (DECOMP / "symbol_addrs.us.txt").read_text().splitlines():
        m = re.match(r"^\s*([A-Za-z_]\w*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;(.*)$", line)
        if m and "type:func" not in m.group(3):
            out.setdefault(int(m.group(2), 16), m.group(1))
    return out


def split_data_in_text(labels, lo, hi, names):
    """Split labels at symbol_addrs names inside [lo, hi)."""
    out = []
    for l in labels:
        cuts = sorted(a for a in names if l.vram < a < l.vram + l.size and lo <= a < hi)
        if not cuts:
            if l.vram in names and names[l.vram] != l.name:
                REPORT.note(f"data-in-text: {l.name} also named {names[l.vram]}")
            out.append(l)
            continue
        bounds = [l.vram] + cuts + [l.vram + l.size]
        for s, e in zip(bounds, bounds[1:]):
            n = l.name if s == l.vram else names[s]
            nl = Label(n, s, l.seg, l.file, l.kind)
            off = s - l.vram
            nl.data = bytearray(l.data[off:e - l.vram])
            nl.size = e - s
            nl.relocs = {o - off: v for o, v in l.relocs.items() if off <= o < e - l.vram}
            nl.widths = {o - off: v for o, v in l.widths.items() if off <= o < e - l.vram}
            out.append(nl)
    return out


def collect_labels(index, elves=None):
    files = {seg: [] for seg in SEGMENTS}
    asm = DECOMP / "asm"
    files["boot"] += sorted((asm / "data").glob("*.s"))
    for sub in ("gu", "io", "vimodes"):
        files["boot"] += sorted((asm / "data/libultra" / sub).glob("*.s"))
    files["global"] += sorted((asm / "global/data").glob("*.s"))
    files["global"] += sorted((asm / "global/nonmatchings").rglob("*.s"))
    files["global"] += [asm / f for f in ("global/1F9A0.s", "global/124780.s", "global/16B60.s")]
    for o in OVERLAYS:
        files[o] += sorted((asm / o / "data").glob("*.s"))
        files[o] += sorted((asm / o / "nonmatchings").rglob("*.s"))
    names = symbol_addrs()
    per_seg = {}
    for seg, fl in files.items():
        out = []
        for f in fl:
            labels = parse_asm_file(f, seg)
            rel = str(f.relative_to(DECOMP))
            if rel in DATA_IN_TEXT:
                lo, hi = DATA_IN_TEXT[rel]
                labels = [l for l in labels if lo <= l.vram < hi]
                labels = split_data_in_text(labels, lo, hi, names)
                for l in labels:
                    l.kind = "rodata"
            kept = []
            for l in labels:
                if l.name.startswith("jtbl_"):
                    continue
                if l.name in index.c_defined:
                    REPORT.note(f"{l.name}: defined in C, skipped")
                    continue
                kept.append(l)
            out.extend(kept)
        if elves is not None:
            out = split_interior(out, seg, index, elves)
            out.extend(shadow_labels(seg, elves))
        per_seg[seg] = out
    return per_seg


def elf_bytes(elves, seg, vram, size):
    with open(elves[seg].path, "rb") as fh:
        elf = ELFFile(fh)
        for sec in elf.iter_sections():
            a = sec["sh_addr"]
            if sec["sh_type"] == "SHT_PROGBITS" and a <= vram and vram + size <= a + sec["sh_size"]:
                return sec.data()[vram - a:vram - a + size]
    return None


def shadow_labels(seg, elves):
    """port/shadow_data.txt: `NAME SIZE` emits NAME as a read-only snapshot of the original big-endian bytes at its
    address. For aliases into C objects whose native layout differs (e.g. byte reads inside a function-pointer
    table) and which the game never writes."""
    path = ROOT / "port" / "shadow_data.txt"
    out = []
    if not path.exists():
        return out
    abs_syms = parse_undefined_syms()
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, size = line.split()
        vram = abs_syms.get(name)
        if vram is None:
            REPORT.error(f"shadow_data.txt: {name} has no address")
            continue
        lseg = "boot" if vram < OVL_VRAM[0] else "global"
        if lseg != seg:
            continue
        data = elf_bytes(elves, seg, vram, int(size, 0))
        if data is None:
            REPORT.error(f"shadow_data.txt: {name} not inside a {seg} section")
            continue
        l = Label(name, vram, seg, f"shadow:{name}", "rodata")
        l.data = bytearray(data)
        l.size = len(data)
        l.widths = {o: 1 for o in range(l.size)}
        REPORT.note(f"shadow {name}: 0x{l.size:X} original bytes")
        out.append(l)
    return out


def split_interior(labels, seg, index, elves):
    """C-declared names placed inside a generated label become labels of their own (contiguous, so the layout
    is unchanged); names placed exactly at a label's start become aliases of it. Candidates are the segment
    ELF's defined symbols plus absolute symbols the decomp links by value (boot/global addresses only)."""
    names = {l.name for l in labels}
    cuts = defaultdict(dict)
    starts = sorted((l.vram, i) for i, l in enumerate(labels))
    keys = [s[0] for s in starts]
    cands = {}
    for n, (addr, size, typ) in elves[seg].defined.items():
        if typ != "STT_FUNC":
            cands[n] = addr
    if seg in ("boot", "global"):
        for n, v in parse_undefined_syms().items():
            if 0x80000000 <= v < 0x80800000 and not (OVL_VRAM[0] <= v < OVL_VRAM[1]):
                if (seg == "boot") == (v < OVL_VRAM[0]):
                    cands.setdefault(n, v)
    else:
        # names the overlay's own link resolved by value inside its VRAM
        path = DECOMP / "build" / f"undefined_syms_auto.{seg}.txt"
        if path.exists():
            for m in re.finditer(r"^\s*([A-Za-z_]\w*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;", path.read_text(), re.M):
                v = int(m.group(2), 16)
                if OVL_VRAM[0] <= v < OVL_VRAM[1]:
                    cands.setdefault(m.group(1), v)
    for n, addr in cands.items():
        if n in names or n in index.c_defined or n not in index.declared:
            continue
        i = bisect.bisect_right(keys, addr) - 1
        if i < 0:
            continue
        l = labels[starts[i][1]]
        if l.vram == addr:
            l.aliases.append(n)
            REPORT.note(f"alias {n} = {l.name}")
        elif l.vram < addr < l.vram + l.size:
            cuts[starts[i][1]][addr] = n
    out = []
    for i, l in enumerate(labels):
        if i not in cuts:
            out.append(l)
            continue
        for a, n in sorted(cuts[i].items()):
            REPORT.note(f"interior label {n} split out of {l.name}+0x{a - l.vram:X}")
        out.extend(split_data_in_text([l], l.vram, l.vram + l.size, cuts[i]))
    return out


