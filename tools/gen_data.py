def load_data_types():
    path = ROOT / "port" / "data_types.txt"
    out = {}
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            m = re.match(r"^(\w+)\s+raw$", line)
            if m:
                out[m.group(1)] = "raw"
                continue
            m = re.match(r"^file\s+(\S+)\s*=\s*(.+)$", line)
            if m:
                out["@file:" + m.group(1)] = m.group(2).strip()
                continue
            m = re.match(r"^(\w+)\s*=\s*(.+)$", line)
            if m:
                out[m.group(1)] = m.group(2).strip()
                continue
            REPORT.error(f"data_types.txt: bad line {line!r}")
    return out


def flatten_override(ctype):
    import clang.cindex as ci
    src = f"#include \"common.h\"\n__typeof__({ctype}) __probe;\n"
    idx = ci.Index.create()
    tu = idx.parse("probe.c", args=game_flags(), unsaved_files=[("probe.c", src)])
    for c in tu.cursor.get_children():
        if c.kind == ci.CursorKind.VAR_DECL and c.spelling == "__probe":
            return flatten_type(c.type, REPORT)
    return None


